#Requires -Version 7.0
<#
.SYNOPSIS
    Register 7003_Repair-DeployRoot as an unattended self-heal task, and page when it cannot fix.

.DESCRIPTION
    7003 is the diagnose-and-fix. This makes it AUTOMATIC, because a maintenance script that
    only runs when someone remembers is documentation, not maintenance — the same failure
    that left 21 of 22 quality checkers running nowhere.

    WHY A SCHEDULED TASK AND NOT A ROUTINE. The deploy-root split is host-side: the drift is
    between two Windows checkouts, and the repair needs `git` and `docker` on the host. A
    routine runs inside the worker container, which can reach docker but CANNOT write to the
    host's deploy checkout. So the fleet routine (`debt-gate-probe`) DETECTS this class via
    check_tree_drift, and this task is what can actually REPAIR it. Detection without a
    repair path is how the same drift recurred three times.

    `schtasks` and not `Register-ScheduledTask`: the cmdlet hangs on this host (same finding
    as register-protonbridge-watchdog.ps1). ONLOGON + `/rl LIMITED` so it runs as the
    logged-on user and keeps Docker-pipe access — SYSTEM cannot reach the Docker Desktop
    pipe here, which would make every run exit 2.

    PAGING. On a run that ends 1 (drift it could not fully repair) or 2 (could not
    determine), the wrapper POSTs to the same Pulse alert webhook Alertmanager uses, so this
    surfaces where every other fleet alert does. A silent self-healer is indistinguishable
    from a broken one.

.PARAMETER IntervalMinutes
    How often to re-check after logon. Default 240 (matches the debt-gate-probe routine, so
    detection and repair stay in step).

.PARAMETER TaskName
    Scheduled task name. Default 'AitherOS-DeployRootSelfHeal'.

.PARAMETER NoFix
    Register in report-only mode (no -Fix). Use to observe before letting it repair.

.PARAMETER Unregister
    Remove the task.

.PARAMETER SelfTest
    Verify the generated command line and paging payload without touching the scheduler.

.EXAMPLE
    .\7004_Register-DeployRootSelfHeal.ps1
    Register the 4-hourly self-heal.

.EXAMPLE
    .\7004_Register-DeployRootSelfHeal.ps1 -NoFix
    Register in report-only mode first.

.EXAMPLE
    .\7004_Register-DeployRootSelfHeal.ps1 -Unregister

.NOTES
    Category: maintenance
    Dependencies: 7003_Repair-DeployRoot.ps1, schtasks, pwsh 7
    Platform: Windows
#>

[CmdletBinding()]
param(
    [int]$IntervalMinutes = 240,
    [string]$TaskName = 'AitherOS-DeployRootSelfHeal',
    [switch]$NoFix,
    [switch]$Unregister,
    [switch]$SelfTest
)

$ErrorActionPreference = 'Stop'

$repairScript = Join-Path $PSScriptRoot '7003_Repair-DeployRoot.ps1'
$runnerScript = Join-Path $PSScriptRoot '.deploy-root-selfheal-run.ps1'
$logPath = Join-Path ([System.IO.Path]::GetTempPath()) 'aitheros-deployroot-selfheal.log'
# MEASURED 2026-07-30: this task runs on the HOST, and the host cannot resolve container
# DNS -- 'aitheros-pulse' returns "No such host is known", so every page this self-heal
# ever tried to send died at name resolution. The runner logs the failure rather than
# swallowing it, but nobody reads that log: an alert path that cannot reach a human is
# indistinguishable from a quiet fleet, which is the exact class this self-heal exists to
# catch. Pulse publishes to 127.0.0.1:8081, so page THAT.
#
# 127.0.0.1 literal, never 'localhost': the IPv6 path hangs on this host (~2s/conn floor
# even on the v4 path -- a host->container POST measured 2.1s, so the timeout below is
# generous on purpose).
$pulseWebhook = 'https://127.0.0.1:8081/alerts/webhook'

function New-RunnerScript {
    <#  The wrapper the task actually invokes.

        It exists so the scheduled command line stays short and quoting-free (schtasks /tr
        mangles nested quotes), and so paging lives in one readable place rather than in a
        one-liner nobody can audit. #>
    param([string]$Path, [bool]$WithFix)

    $fixArg = if ($WithFix) { " -Fix" } else { "" }
    $content = @"
# GENERATED by 7004_Register-DeployRootSelfHeal.ps1 — edit that, not this.
`$ErrorActionPreference = 'Continue'
`$repair = '$repairScript'
`$log    = '$logPath'
`$hook   = '$pulseWebhook'

`$stamp = (Get-Date).ToString('s')
`$json  = & pwsh -NoProfile -File `$repair -Json$fixArg 2>&1 | Out-String
`$code  = `$LASTEXITCODE
Add-Content -Path `$log -Value "[`$stamp] exit=`$code `$(`$json.Trim())"

# Keep the log bounded; an unbounded self-heal log is its own incident.
if ((Test-Path `$log) -and ((Get-Item `$log).Length -gt 2MB)) {
    `$keep = Get-Content `$log -Tail 500
    Set-Content -Path `$log -Value `$keep
}

if (`$code -eq 0) { exit 0 }

# 1 = drift it could not fully repair. 2 = could not determine (docker down, no git).
# BOTH page: "the self-healer cannot tell" must never look like "everything is fine".
`$severity = if (`$code -eq 2) { 'warning' } else { 'critical' }
`$summary  = if (`$code -eq 2) {
    'Deploy-root self-heal could not determine the deploy root (docker down?)'
} else {
    'Deploy-root drift persists after automatic repair — the fleet may be running code that is not in the repo'
}
`$body = @{
    alerts = @(@{
        status = 'firing'
        labels = @{
            alertname = 'DeployRootDriftUnrepaired'
            severity  = `$severity
            service   = 'deploy-root'
        }
        annotations = @{
            summary     = `$summary
            description = `$json.Trim()
            runbook     = 'AitherZero 70-maintenance/7003_Repair-DeployRoot.ps1 -Fix'
        }
    })
} | ConvertTo-Json -Depth 6 -Compress

# MEASURED 2026-07-30: from a COLD ``pwsh -NoProfile -File`` process -- which is exactly how
# the scheduled task runs -- Invoke-RestMethod to this endpoint timed out at 20s on 2 of 3
# consecutive attempts, while curl.exe to the same URL completed in ~2.1s every time. From a
# warm interactive shell Invoke-RestMethod returns in 0s, so this NEVER reproduces when you
# test it by hand; it only fails in the one context that matters. An alert path that drops
# two thirds of its pages is worse than no alert path, because the log line it leaves behind
# is the only evidence and nobody reads a log that usually says nothing.
#
# So: curl.exe first (present in System32 on Win10+), Invoke-RestMethod as the fallback, and
# retry either way. Every attempt is logged -- a page that only succeeded on retry is a
# degradation worth seeing, not a success worth hiding.
`$bodyFile = Join-Path ([System.IO.Path]::GetTempPath()) ("deployroot-page-" + [guid]::NewGuid().ToString('N').Substring(0,8) + ".json")
Set-Content -Path `$bodyFile -Value `$body -Encoding UTF8
`$paged = `$false
`$curl = Join-Path `$env:SystemRoot 'System32\curl.exe'
foreach (`$attempt in 1..3) {
    try {
        if (Test-Path `$curl) {
            `$out = & `$curl -sS -k --max-time 45 -X POST -H 'Content-Type: application/json' --data-binary "@`$bodyFile" -w '%{http_code}' `$hook 2>&1 | Out-String
            if (`$LASTEXITCODE -eq 0 -and `$out -match '200') { `$paged = `$true }
            else { throw "curl exit=`$LASTEXITCODE out=`$(`$out.Trim())" }
        } else {
            Invoke-RestMethod -Uri `$hook -Method Post -Body `$body -ContentType 'application/json' -SkipCertificateCheck -TimeoutSec 45 | Out-Null
            `$paged = `$true
        }
    } catch {
        Add-Content -Path `$log -Value "[`$stamp] page attempt `$attempt failed: `$(`$_.Exception.Message)"
    }
    if (`$paged) {
        `$note = if (`$attempt -gt 1) { " (on attempt `$attempt)" } else { '' }
        Add-Content -Path `$log -Value "[`$stamp] paged (`$severity)`$note"
        break
    }
    Start-Sleep -Seconds (2 * `$attempt)
}
Remove-Item `$bodyFile -Force -ErrorAction SilentlyContinue
if (-not `$paged) {
    # Do not swallow: if paging fails the operator must be able to see that in the log,
    # otherwise a broken alert path looks like a quiet fleet.
    Add-Content -Path `$log -Value "[`$stamp] PAGING FAILED after 3 attempts"
}
exit `$code
"@
    Set-Content -Path $Path -Value $content -Encoding UTF8
}

function Invoke-SelfTest {
    $fail = [System.Collections.Generic.List[string]]::new()

    if (-not (Test-Path $repairScript)) { $fail.Add("repair script missing: $repairScript") }

    $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("shrun-" + [guid]::NewGuid().ToString('N').Substring(0, 8) + ".ps1")
    try {
        New-RunnerScript -Path $tmp -WithFix $true
        $text = Get-Content $tmp -Raw

        # It must parse — a generated runner that cannot parse fails silently at 3am.
        $errs = $null
        [System.Management.Automation.Language.Parser]::ParseFile($tmp, [ref]$null, [ref]$errs) | Out-Null
        if ($errs) { $fail.Add("generated runner does not parse: $($errs[0].Message)") }

        foreach ($needle in @('-Json', '-Fix', 'DeployRootDriftUnrepaired', 'PAGING FAILED')) {
            if ($text -notmatch [regex]::Escape($needle)) { $fail.Add("generated runner is missing '$needle'") }
        }
        # Both non-zero codes must page; only 0 may exit quietly.
        if ($text -notmatch 'if \(\$code -eq 0\) \{ exit 0 \}') { $fail.Add('runner does not short-circuit on exit 0') }
        if ($text -notmatch "code -eq 2") { $fail.Add('runner does not distinguish exit 2 (cannot determine)') }

        # Report-only mode must NOT carry -Fix, or -NoFix silently repairs anyway.
        New-RunnerScript -Path $tmp -WithFix $false
        $noFixText = Get-Content $tmp -Raw
        if ($noFixText -match '-Json -Fix') { $fail.Add('-NoFix still generated a -Fix invocation') }
    } finally {
        if (Test-Path $tmp) { Remove-Item $tmp -Force -ErrorAction SilentlyContinue }
    }

    # The page must be able to LEAVE this host. A container hostname resolves inside the
    # docker network and nowhere else, so a task scheduled on the host silently fails every
    # page at name resolution -- which reads exactly like a fleet with nothing to report.
    # Assert the URL is host-reachable AND that name resolution really succeeds.
    $hookHost = ([uri]$pulseWebhook).Host
    if ($hookHost -like 'aitheros-*') {
        $fail.Add("webhook host '$hookHost' is a container name — unreachable from the host")
    }
    if ($hookHost -eq 'localhost') {
        $fail.Add("webhook host 'localhost' resolves ::1 first and hangs here — use 127.0.0.1")
    }
    if ($hookHost -ne '127.0.0.1') {
        try { [System.Net.Dns]::GetHostEntry($hookHost) | Out-Null }
        catch { $fail.Add("webhook host '$hookHost' does not resolve from this host") }
    }

    if ($fail.Count -gt 0) {
        Write-Host 'SELF-TEST FAILED' -ForegroundColor Red
        $fail | ForEach-Object { Write-Host "  - $_" -ForegroundColor Red }
        return 1
    }
    Write-Host 'SELF-TEST PASSED - runner parses, pages on 1 and 2, honours -NoFix, and the webhook host is reachable from the host' -ForegroundColor Green
    return 0
}

if ($SelfTest) { exit (Invoke-SelfTest) }

if ($Unregister) {
    & schtasks /delete /tn $TaskName /f
    Write-Host "Unregistered '$TaskName' (exit $LASTEXITCODE)." -ForegroundColor Green
    if (Test-Path $runnerScript) { Remove-Item $runnerScript -Force -ErrorAction SilentlyContinue }
    exit 0
}

if (-not (Test-Path $repairScript)) {
    Write-Host "CANNOT REGISTER: $repairScript not found." -ForegroundColor Red
    exit 2
}

New-RunnerScript -Path $runnerScript -WithFix (-not $NoFix)

$pwshExe = (Get-Command pwsh).Source
Write-Host ''
Write-Host "Task     : $TaskName" -ForegroundColor Cyan
Write-Host "Runs     : $runnerScript"
Write-Host "Mode     : $(if ($NoFix) { 'report-only' } else { 'diagnose + repair (-Fix)' })"
Write-Host "Schedule : ONLOGON, then every $IntervalMinutes min" -ForegroundColor Cyan
Write-Host "Log      : $logPath"
Write-Host "Pages to : $pulseWebhook (on exit 1 and 2)"
Write-Host ''

# ONLOGON so it runs as the logged-on user: SYSTEM cannot reach the Docker Desktop pipe on
# this host, which would make every run exit 2 and page forever.
#
# MEASURED 2026-07-30: `/sc ONLOGON` requires elevation even with `/rl LIMITED`, while
# `/sc MINUTE` does not. This script used to `exit 1` the moment ONLOGON was denied, which
# meant an unelevated run registered NOTHING -- not even the interval trigger that needs no
# elevation and carries the actual recurring coverage. So "needs one elevated run" was true
# of the boot trigger and got mis-stated as true of the whole self-heal. Degrade instead:
# take the coverage that is available and say exactly what is missing.
$logonOk = $false
& schtasks /create /tn $TaskName /tr "`"$pwshExe`" -NoProfile -WindowStyle Hidden -File `"$runnerScript`"" /sc ONLOGON /rl LIMITED /f 2>&1 | Write-Host
if ($LASTEXITCODE -eq 0) { $logonOk = $true }
else {
    Write-Host "ONLOGON trigger DENIED (needs elevation) - continuing without it" -ForegroundColor Yellow
}

# The interval trigger. ONLOGON alone would only self-heal at logon, and this host stays
# logged in for days -- so this is the trigger that does the real work, not a supplement.
& schtasks /create /tn "$TaskName-Interval" /tr "`"$pwshExe`" -NoProfile -WindowStyle Hidden -File `"$runnerScript`"" /sc MINUTE /mo $IntervalMinutes /rl LIMITED /f 2>&1 | Write-Host
$intervalOk = ($LASTEXITCODE -eq 0)

Write-Host ''
if ($intervalOk) {
    & schtasks /query /tn "$TaskName-Interval" /fo list | Select-String -Pattern 'TaskName:|Status:|Task To Run:'
    Write-Host ''
    Write-Host "Registered: self-heal runs every $IntervalMinutes min." -ForegroundColor Green
    if ($logonOk) {
        Write-Host "Boot coverage: ONLOGON trigger active." -ForegroundColor Green
    } else {
        Write-Host "Boot coverage: MISSING. After a reboot the first check waits up to $IntervalMinutes min." -ForegroundColor Yellow
        Write-Host "To add it, run ONCE from an elevated shell:" -ForegroundColor Yellow
        Write-Host "  schtasks /create /tn $TaskName /tr '`"$pwshExe`" -NoProfile -WindowStyle Hidden -File `"$runnerScript`"' /sc ONLOGON /rl LIMITED /f"
    }
    Write-Host "First run now: schtasks /run /tn $TaskName-Interval" -ForegroundColor Green
    exit 0
}

# No interval trigger => no recurring coverage at all. That is a real failure.
Write-Host "FAILED: could not register the interval trigger - there is NO recurring self-heal." -ForegroundColor Red
exit 1
